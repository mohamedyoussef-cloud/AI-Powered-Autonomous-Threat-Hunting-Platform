_DEFAULT_PATTERN = {
    "keywords": [],
    "logsource_category": "process_creation",
    "selection": {"CommandLine|contains": "REPLACE_WITH_INDICATOR"},
    "default_technique": None,
    "level": "medium",
}


@dataclass
class RuleDraft:
    yaml_text: str
    matched_pattern_keywords: list[str]


def _slugify_title(text: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", text)
    return " ".join(w.capitalize() for w in words[:8]) or "Untitled Hunting Hypothesis"


def generate_rule_draft(
    hypothesis_text: str,
    target_technique_id: str | None,
    target_platform: str,
    detection_objective: str | None = None,
    observable_behaviors: list[str] | None = None,
    known_limitations: list[str] | None = None,
) -> RuleDraft:
    observable_behaviors = observable_behaviors or []
    known_limitations = known_limitations or []

    context_parts = [
        hypothesis_text.strip(),
        detection_objective.strip() if detection_objective else "",
        " ".join(x.strip() for x in observable_behaviors if x.strip()),
    ]
    text_lower = " ".join(x for x in context_parts if x).lower()

    matched = _DEFAULT_PATTERN
    for pattern in _PATTERNS:
        if any(kw in text_lower for kw in pattern["keywords"]):
            matched = pattern
            break

    technique_id = target_technique_id or matched["default_technique"]
    tags_block = f"  - attack.{technique_id.lower()}\n" if technique_id else ""

    selection_lines = "\n".join(
        f"    {k}: '{v}'" if isinstance(v, str) else f"    {k}: {v}"
        for k, v in matched["selection"].items()
    )

    title = _slugify_title(hypothesis_text)
    yaml_text = f"""title: {title} (DRAFT)
id: {uuid.uuid4()}
status: experimental
description: >
  Auto-drafted from hunting hypothesis: "{hypothesis_text.strip()}"
  This is a TEMPLATE-GENERATED draft — review and refine before use.
  Generated by template_v0, not the platform's LLM Hypothesis Engine.
author: Sigma Rule Generator (template_v0 — placeholder)
tags:
{tags_block}logsource:
  category: {matched['logsource_category']}
  product: {target_platform}
detection:
  selection:
{selection_lines}
  condition: selection
level: {matched['level']}
falsepositives:
  - Unreviewed draft — false positive analysis not yet performed
"""
    return RuleDraft(yaml_text=yaml_text, matched_pattern_keywords=matched["keywords"])
