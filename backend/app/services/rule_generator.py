"""
services/rule_generator.py
------------------------------
IMPORTANT — read this before trusting this module's output for anything
beyond UI/API contract testing:

This is a deterministic KEYWORD-TEMPLATE engine, not the platform's real
Hypothesis Engine (which the architecture describes as a locally hosted
Mistral-7B model doing RAG-grounded generation against the ATT&CK +
Sigma corpus). It exists so the Sigma Rule Generator screen, its API
contract, and its downstream validation step (this DOES run the drafted
YAML through the real pySigma parser from the data-prep pipeline) are
fully wired up and testable NOW — the day the real LLM is ready, it
slots in behind generate_rule_draft() without changing the API,
database schema, or frontend at all.

Every response from this module says so explicitly (generation_method =
"template_v0", plus a `warning` string) — nothing here should ever be
presented to an end user as an LLM-generated detection.
"""
from __future__ import annotations

import re
import uuid
from dataclasses import dataclass

