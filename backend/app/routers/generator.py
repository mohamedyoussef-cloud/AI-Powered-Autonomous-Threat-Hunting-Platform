"""
routers/generator.py
-----------------------
Sigma Rule Generator endpoint. Drafts a rule from a template engine
(services/rule_generator.py — see its docstring for the honest caveat
about what this is and isn't), then runs the draft through the SAME
real pySigma validation used by the data-prep pipeline, so the response
tells the user whether their draft is even structurally valid Sigma —
not just "here's some text that looks like YAML".
"""
from __future__ import annotations

import sys
from pathlib import Path

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from app.core.config import get_settings
from app.core.database import get_db
from app.models.generator import GeneratedRuleRequest
from app.schemas.api_schemas import GenerateRuleRequest, GenerateRuleResponse
from app.services.rule_generator import generate_rule_draft

router = APIRouter(prefix="/generator", tags=["generator"])
settings = get_settings()

# Reuse the real pySigma-backed parser from the data-prep pipeline
# instead of re-implementing Sigma validation here.
_PIPELINE_SRC = Path(settings.PIPELINE_DATA_ROOT).parent / "src"
if _PIPELINE_SRC.exists() and str(_PIPELINE_SRC) not in sys.path:
    sys.path.insert(0, str(_PIPELINE_SRC))

try:
    from parsers.sigma_parser import parse_sigma_rule  # type: ignore
    _VALIDATION_AVAILABLE = True
except ImportError:
    _VALIDATION_AVAILABLE = False


@router.get("/providers")
def providers():
    """Detection-synthesis sources and whether each one is usable right now."""
    from app.services.detection_providers import describe_all
    return {"items": describe_all()}


@router.post("/generate-rule", response_model=GenerateRuleResponse)
def generate_rule(payload: GenerateRuleRequest, db: Session = Depends(get_db)):
    from app.services import detection_providers as dp
    from app.services.sigma_engine import validate_rule
    try:
        prov = dp.get(payload.provider)
    except KeyError:
        raise HTTPException(400, f"Unknown provider '{payload.provider}'")
    try:
        out = prov.generate(db, payload.hypothesis_text, payload.target_technique_id, payload.target_platform)
    except dp.ProviderUnavailable as exc:
        raise HTTPException(409, f"{prov.label} is not available: {exc}")
    if not out:
        raise HTTPException(404, f"{prov.label} found no rule for {payload.target_technique_id or 'this hypothesis'}. Try another source.")
    g = out[0]
    v = validate_rule(g.yaml_text, None, payload.target_technique_id)  # mandatory gate, every provider
    gate = {"executable": v["executable"], "issues": [i.dict() for i in v["issues"]], "techniques": v["techniques"]}
    validation_note = "Optional pySigma structural validation unavailable; rule requires review. "
    if _VALIDATION_AVAILABLE:
        result = parse_sigma_rule(g.yaml_text)
        validation_note = ("pySigma structural validation passed. " if result.ok and result.rule.validation.sigma_schema_valid
                           else f"pySigma validation issue: {getattr(result, 'fatal_errors', '')}. ")
    row = GeneratedRuleRequest(hypothesis_text=payload.hypothesis_text, target_technique_id=payload.target_technique_id,
                               target_platform=payload.target_platform, generated_yaml=g.yaml_text,
                               generation_method=g.method, status="draft" if v["executable"] else "rejected")
    db.add(row)
    db.commit()
    db.refresh(row)
    if g.method == "template_v0":
        warn = "Produced by a keyword template, not an LLM. Review before use. "
    elif g.method == "llm_qwen3":
        warn = "Generated by the fine-tuned LLM. Untrusted until reviewed; the validation gate result is shown below. "
    else:
        warn = f"Selected from the curated Sigma corpus ({g.note}). "
    if not v["executable"]:
        warn += "BLOCKED by the validation gate: " + "; ".join(i.message for i in v["issues"] if i.severity == "error") + ". "
    return GenerateRuleResponse(id=row.id, generated_yaml=g.yaml_text, generation_method=g.method, status=row.status,
                                warning=warn + validation_note, provider=prov.id, gate=gate)
